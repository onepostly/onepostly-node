#!/usr/bin/env npx tsx
/**
 * Generate endpoint-existence tests from the OpenAPI spec.
 *
 * For every operation in the spec the generated vitest suite asserts that the
 * corresponding SDK method exists on the right API class. This catches any
 * endpoint that regenerates into the client without being surfaced (or gets
 * dropped from the spec while still claimed by the README).
 *
 * Run manually or from the generate workflow; output is committed.
 */
import { readFile, writeFile } from "node:fs/promises";

const DEFAULT_SPEC_URL = "https://api.onepostly.com/openapi.json";
const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete"]);

interface Operation {
  operationId: string;
}

interface ParsedArgs {
  spec: string | null;
  out: string;
}

interface OpenApiSpec {
  paths?: Record<string, Record<string, { tags?: string[]; operationId?: string }>>;
}

function parseArgs(argv: string[]): ParsedArgs {
  const args: ParsedArgs = { spec: null, out: "tests/endpoints.test.ts" };
  for (let i = 2; i < argv.length; i += 1) {
    if (argv[i] === "--spec") args.spec = argv[(i += 1)];
    else if (argv[i] === "--out") args.out = argv[(i += 1)];
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

async function loadSpec(args: ParsedArgs): Promise<OpenApiSpec> {
  if (args.spec) return JSON.parse(await readFile(args.spec, "utf8")) as OpenApiSpec;
  const res = await fetch(DEFAULT_SPEC_URL);
  if (!res.ok) throw new Error(`Failed to fetch spec from ${DEFAULT_SPEC_URL}: ${res.status}`);
  return (await res.json()) as OpenApiSpec;
}

function collectEndpoints(spec: OpenApiSpec): Map<string, string[]> {
  const classes = new Map<string, string[]>();
  for (const methods of Object.values(spec.paths ?? {})) {
    for (const [verb, op] of Object.entries(methods)) {
      if (!HTTP_METHODS.has(verb) || !op.tags?.[0] || !op.operationId) continue;
      const className = `${op.tags[0]}Api`;
      if (!classes.has(className)) classes.set(className, []);
      classes.get(className)!.push(op.operationId);
    }
  }
  for (const methods of classes.values()) methods.sort();
  return classes;
}

function generateTestFile(spec: OpenApiSpec): string {
  const classes = collectEndpoints(spec);
  const lines: string[] = [
    "/**",
    " * Auto-generated endpoint tests from the OpenAPI spec.",
    " *",
    " * DO NOT EDIT THIS FILE MANUALLY.",
    " * Run `npm run generate:endpoint-tests` to regenerate.",
    " */",
    "",
    'import { describe, expect, it } from "vitest";',
    'import { Configuration } from "../src/index.js";',
    "",
  ];
  for (const className of classes.keys()) {
    lines.push(`import { ${className} } from "../src/index.js";`);
  }
  lines.push(
    "",
    "const config = new Configuration({ apiKey: \"op_test\" });",
    "",
    'describe("spec endpoints surface as SDK methods", () => {',
  );
  for (const [className, methods] of classes) {
    lines.push(`  describe("${className}", () => {`);
    for (const method of methods) {
      lines.push(`    it("exposes ${method}", () => {`);
      lines.push(`      expect(typeof new ${className}(config)[${JSON.stringify(method)}]).toBe("function");`);
      lines.push("    });");
    }
    lines.push("  });", "");
  }
  lines.push("});", "");
  return lines.join("\n");
}

const args = parseArgs(process.argv);
const content = generateTestFile(await loadSpec(args));
await writeFile(args.out, content);
console.log(`Endpoint tests generated in ${args.out}.`);
